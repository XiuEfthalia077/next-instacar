create policy "public read car-images" on storage.objects
  for select using (bucket_id in ('car-images', 'site-assets'));

-- Booking uploads: owner (customer folder) or admin/staff can read.
drop policy if exists "booking-uploads read" on storage.objects;
create policy "booking-uploads read" on storage.objects
  for select using (
    bucket_id = 'booking-uploads'
    and (
      public.is_admin()
      or public.current_user_role() = 'staff'
      or public.current_user_role() = 'operator'
      or (storage.foldername(name))[1] like (
            (select replace(u.name, ' ', '_') from public.users u where u.auth_id = auth.uid()) || '_%'
          )
    )
  );

drop policy if exists "booking-uploads write" on storage.objects;
create policy "booking-uploads write" on storage.objects
  for insert with check (bucket_id = 'booking-uploads');

