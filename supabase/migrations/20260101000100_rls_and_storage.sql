-- Mirrors config/booking_scope_helper.php :: userCanAccessBooking()
--   admin    -> any booking
--   staff    -> bookings whose car belongs to the staff branch
--   operator -> bookings whose car is owned by the operator
--   user     -> own bookings
create or replace function public.user_can_access_booking(p_booking_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.bookings b
    join public.cars c on b.car_id = c.id
    where b.id = p_booking_id
      and case public.current_user_role()
        when 'admin'    then true
        when 'staff'    then c.branch_id is not null
                            and c.branch_id = public.current_user_branch_id()
        when 'operator' then c.user_id = public.current_user_id()
        when 'user'     then b.user_id = public.current_user_id()
        else false
      end
  );
$$;

-- Mirrors config/branch_helper.php :: branchScopeSql('branch_id')
-- Admins pass an explicit branch id (or null = all branches).
create or replace function public.branch_scope(p_branch_id bigint)
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select case
    when public.current_user_role() = 'admin' then p_branch_id
    when public.current_user_role() in ('staff', 'operator') then public.current_user_branch_id()
    else null
  end;
$$;

-- Mirrors the availability overlap rule from METHODOLOGY.md:
--   requested_start <= existing_end AND requested_end >= existing_start
create or replace function public.car_is_available(
  p_car_id bigint,
  p_start_date date,
  p_end_date date,
  p_pickup_time time default null,
  p_return_time time default null,
  p_exclude_booking_id bigint default null
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    not exists (
      select 1
      from public.bookings b
      where b.car_id = p_car_id
        and b.status not in ('Cancelled', 'Completed')
        and (p_exclude_booking_id is null or b.id <> p_exclude_booking_id)
        and (
          case
            when p_pickup_time is null or p_return_time is null then
              b.start_date <= p_end_date and b.end_date >= p_start_date
            else
              (b.start_date + b.pickup_time) < (p_end_date + p_return_time)
              and (b.end_date + b.return_time) > (p_start_date + p_pickup_time)
          end
        )
    )
    and not exists (
      select 1
      from public.car_schedules cs
      where cs.car_id = p_car_id
        and cs.start_date <= p_end_date
        and cs.end_date >= p_start_date
    );
$$;

