-- ---------------------------------------------------------------------------
-- 1. password_resets (OTP Verification Flow)
-- ---------------------------------------------------------------------------
create table if not exists public.password_resets (
  id            bigint generated by default as identity primary key,
  email         varchar(255) not null,
  otp_hash      varchar(255) not null,
  reset_token   text default null,
  attempts      integer not null default 0,
  expires_at    timestamptz not null,
  consumed_at   timestamptz default null,
  created_at    timestamptz not null default now()
);

create index if not exists idx_password_resets_email on public.password_resets(email);
create index if not exists idx_password_resets_lookup on public.password_resets(email, expires_at, consumed_at);
create index if not exists idx_password_resets_token on public.password_resets(reset_token) where reset_token is not null;

alter table public.password_resets enable row level security;

-- Only service role can access password_resets to protect OTP hashes
drop policy if exists password_resets_service_role on public.password_resets;
create policy password_resets_service_role
  on public.password_resets
  for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');

-- ---------------------------------------------------------------------------
-- 2. inquiries (Landing Page Contact / Inquiry Submissions)
-- ---------------------------------------------------------------------------
create table if not exists public.inquiries (
  id          bigint generated by default as identity primary key,
  name        varchar(100) not null,
  email       varchar(150) not null,
  subject     varchar(200) not null default 'General Inquiry',
  message     text not null,
  is_read     boolean not null default false,
  created_at  timestamptz not null default now()
);

create index if not exists idx_inquiries_created_at on public.inquiries(created_at desc);

alter table public.inquiries enable row level security;

-- Public anon users can submit contact inquiries
drop policy if exists inquiries_public_insert on public.inquiries;
create policy inquiries_public_insert
  on public.inquiries
  for insert
  with check (true);

-- Admins and staff can view inquiries
drop policy if exists inquiries_admin_select on public.inquiries;
create policy inquiries_admin_select
  on public.inquiries
  for select
  using (
    exists (
      select 1 from public.users
      where users.auth_id = auth.uid()
        and users.role in ('admin', 'staff')
    )
  );

-- Admins and staff can update inquiries (e.g., mark as read)
drop policy if exists inquiries_admin_update on public.inquiries;
create policy inquiries_admin_update
  on public.inquiries
  for update
  using (
    exists (
      select 1 from public.users
      where users.auth_id = auth.uid()
        and users.role in ('admin', 'staff')
    )
  );
