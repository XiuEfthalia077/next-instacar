  ext_price_1_6     numeric(10,2) not null default 0.00,
  color             varchar(255) not null default '',
  price_10_hours    numeric(10,2) default 0.00,
  operator_10_hours numeric(10,2) default 0.00,
  price_12_hours    numeric(10,2) default 0.00,
