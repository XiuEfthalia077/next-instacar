-- ---------------------------------------------------------------------------
-- branches
-- ---------------------------------------------------------------------------
create table if not exists public.branches (
  id          bigint generated by default as identity primary key,
  name        varchar(100) not null,
  address     varchar(255) default null,
  phone       varchar(20) default null,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- users  (auth_id links to auth.users)
-- ---------------------------------------------------------------------------
create table if not exists public.users (
  id                 bigint generated by default as identity primary key,
  auth_id            uuid unique references auth.users (id) on delete cascade,
  google_id          varchar(255) default null,
  name               varchar(255) not null,
  email              varchar(255) not null unique,
  password           varchar(255) default null,
  phone              varchar(255) not null default '',
  role               public.user_role not null default 'user',
  branch_id          bigint default null references public.branches (id) on delete set null,
  created_at         timestamptz not null default now(),
  reset_token        varchar(255) default null,
  token_expiry       timestamptz default null,
  verification_token varchar(64) default null,
  is_verified        boolean not null default false
);

create index if not exists idx_users_branch on public.users (branch_id);

